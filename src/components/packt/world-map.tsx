import { type WorldPin } from "@/data/types";

const MASK = [
  "..................................................",
  "...........#####.#####............................",
  ".........###################.....##.##.............",
  "........######################.#####...............",
  ".......##############.#######.######.....##........",
  ".......##############..######.#####.....####.......",
  "........###########.....####..####......##.........",
  "........###########.....##....###..................",
  ".........#########.......#....##...................",
  "..........#######........#...#####.................",
  "...........####..............######...####.........",
  "............##............#..######...####.........",
  "............##............#..#####....###..........",
  ".............#............##..####.....##..........",
  ".............##............##..####................",
  "..............#............##..####................",
  "..............##............#..####................",
  "..............###...........#..###.................",
  "...............##...........#..##..................",
  "................#............#.#...................",
  "................#............#.....................",
  "................#............#.....................",
  "................##..................##.............",
  ".................##............................###.",
  "..................#.................##.........###.",
];

const COLS = MASK[0].length;
const ROWS = MASK.length;
const CELL_W = 1000 / COLS;
const CELL_H = 500 / ROWS;

interface WorldMapProps {
  pins?: WorldPin[];
  size?: "sm" | "lg";
  className?: string;
}

export function WorldMap({ pins = [], size = "lg", className }: WorldMapProps) {
  const r = size === "sm" ? 1.6 : 2.2;

  const dots: React.ReactNode[] = [];
  for (let y = 0; y < ROWS; y++) {
    for (let x = 0; x < COLS; x++) {
      if (MASK[y][x] === "#") {
        dots.push(
          <circle
            key={`${x},${y}`}
            cx={x * CELL_W + CELL_W / 2}
            cy={y * CELL_H + CELL_H / 2}
            r={r}
            fill="var(--fg-4)"
          />
        );
      }
    }
  }

  return (
    <svg
      viewBox="0 0 1000 500"
      preserveAspectRatio="xMidYMid meet"
      className={className}
      style={{ width: "100%", height: "100%" }}
    >
      <g>{dots}</g>
      <g>
        {pins.map((p, pinIdx) => (
          <g key={pinIdx}>
            <circle cx={p.x} cy={p.y} r={9} fill="var(--accent-brand)" fillOpacity={0.18} />
            <circle cx={p.x} cy={p.y} r={4.5} fill="var(--accent-brand)" stroke="var(--bg)" strokeWidth={1.5} />
          </g>
        ))}
      </g>
    </svg>
  );
}
