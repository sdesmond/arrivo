import { type WorldPin } from "@/data/types";

const MASK = [
  "..................................................",
  "...........#####.#####............................",
  ".........###################.....##.##.............",
  "........######################.#####...............",
  ".......##############.#######.######.....##........",
  ".......##############..######.#####.....####.......",
  "........###########.....####..####......##.........",
  "........###########.....##....###..................",
  ".........#########.......#....##...................",
  "..........#######........#...#####.................",
  "...........####..............######...####.........",
  "............##............#..######...####.........",
  "............##............#..#####....###..........",
  ".............#............##..####.....##..........",
  ".............##............##..####................",
  "..............#............##..####................",
  "..............##............#..####................",
  "..............###...........#..###.................",
  "...............##...........#..##..................",
  "................#............#.#...................",
  "................#............#.....................",
  "................#............#.....................",
  "................##..................##.............",
  ".................##............................###.",
  "..................#.................##.........###.",
];

const COLS = MASK[0].length;
const ROWS = MASK.length;
const CELL_W = 1000 / COLS;
const CELL_H = 500 / ROWS;

interface WorldMapProps {
  pins?: WorldPin[];
  size?: "sm" | "lg";
  className?: string;
}

export function WorldMap({ pins = [], size = "lg", className }: WorldMapProps) {
  const radius = size === "sm" ? 1.6 : 2.2;

  const dots: React.ReactNode[] = [];
  for (let row = 0; row < ROWS; row++) {
    for (let col = 0; col < COLS; col++) {
      if (MASK[row][col] === "#") {
        dots.push(
          <circle
            key={`${col},${row}`}
            cx={col * CELL_W + CELL_W / 2}
            cy={row * CELL_H + CELL_H / 2}
            r={radius}
            fill="var(--fg-4)"
          />
        );
      }
    }
  }

  return (
    <svg
      viewBox="0 0 1000 500"
      preserveAspectRatio="xMidYMid meet"
      className={className}
      style={{ width: "100%", height: "100%" }}
    >
      <g>{dots}</g>
      <g>
        {pins.map((pin, pinIdx) => (
          <g key={pinIdx}>
            <circle cx={pin.x} cy={pin.y} r={9} fill="var(--accent-brand)" fillOpacity={0.18} />
            <circle cx={pin.x} cy={pin.y} r={4.5} fill="var(--accent-brand)" stroke="var(--bg)" strokeWidth={1.5} />
          </g>
        ))}
      </g>
    </svg>
  );
}
