// world-map.jsx — stylized dot-grid world map with destination pins
// Dot-grid is built procedurally from a low-res continent mask.

const Packt_WorldMap = (() => {
  // Compact continent mask. 50 cols × 25 rows. # = land, . = water
  // Hand-tuned silhouette; not geographically perfect but reads as a world map.
  const MASK = [
    "..................................................",
    "...........#####.#####............................",
    ".........###################.....##.##.............",
    "........######################.#####...............",
    ".......##############.#######.######.....##........",
    ".......##############..######.#####.....####.......",
    "........###########.....####..####......##.........",
    "........###########.....##....###..................",
    ".........#########.......#....##...................",
    "..........#######........#...#####.................",
    "...........####..............######...####.........",
    "............##............#..######...####.........",
    "............##............#..#####....###..........",
    ".............#............##..####.....##..........",
    ".............##............##..####................",
    "..............#............##..####................",
    "..............##............#..####................",
    "..............###...........#..###.................",
    "...............##...........#..##..................",
    "................#............#.#...................",
    "................#............#.....................",
    "................#............#.....................",
    "................##..................##.............",
    ".................##............................###.",
    "..................#.................##.........###.",
  ];

  function WorldMap({ pins = [], size = 'lg' }) {
    const cols = MASK[0].length;
    const rows = MASK.length;
    const cellW = 1000 / cols;
    const cellH = 500 / rows;
    const r = size === 'sm' ? 1.6 : 2.2;

    const dots = [];
    for (let y = 0; y < rows; y++) {
      for (let x = 0; x < cols; x++) {
        if (MASK[y][x] === '#') {
          dots.push(
            <circle key={`${x},${y}`} cx={x * cellW + cellW/2} cy={y * cellH + cellH/2} r={r} className="wm-dot" />
          );
        }
      }
    }

    return (
      <svg viewBox="0 0 1000 500" preserveAspectRatio="xMidYMid meet" style={{ width: '100%', height: '100%' }}>
        <rect className="wm-bg" x="0" y="0" width="1000" height="500" rx="0" fillOpacity="0" />
        <g>{dots}</g>
        <g>
          {pins.map((p, i) => (
            <g key={i}>
              <circle cx={p.x} cy={p.y} r="9" className="wm-pin" fillOpacity="0.18" />
              <circle cx={p.x} cy={p.y} r="4.5" className="wm-pin wm-pin-stroke" />
            </g>
          ))}
        </g>
      </svg>
    );
  }

  return { WorldMap };
})();

window.Packt_WorldMap = Packt_WorldMap;
